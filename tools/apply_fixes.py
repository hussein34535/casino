FILES = {
    "questions_general.json": (TRIVIA, 2),
    "puzzle.json": (PUZZLE, 4),
    "movies_series.json": (MOVIES, 4),
}


def clean_ans(a: str) -> str:
    a = re.sub(r"\s*\([^()]*\)", "", a)
    return re.sub(r"\s+", " ", a).strip()


def key_forms(key: str):
    return {key, key.replace("'", "\u2019"), key.replace("\u2019", "'")}


def find(data, key):
    forms = key_forms(key)
    return [d for d in data if any(f in d["question"] for f in forms)]


def main():
    warnings = []
    for name, (spec, indent) in FILES.items():
        path = ASSETS / name
        with open(path, encoding="utf-8") as f:
            data = json.load(f)
        n0 = len(data)
        stats = {"fix": 0, "fixq": 0, "del": 0, "multi": 0}

        for entry in spec["fix"]:
            matches = find(data, entry["q"])
            if not matches:
                warnings.append(f"[{name}] FIX no match: {entry['q'][:60]}")
                continue
            if len(matches) > 1:
                stats["multi"] += 1
                warnings.append(f"[{name}] FIX multi({len(matches)}): {entry['q'][:60]}")
            new_a = clean_ans(entry["a"])
            for m in matches:
                m["answer"] = new_a
                stats["fix"] += 1

        for entry in spec.get("fix_question", []):
            matches = find(data, entry["q"])
            if not matches:
                warnings.append(f"[{name}] FIXQ no match: {entry['q'][:60]}")
                continue
            for m in matches:
                m["question"] = entry["new_q"]
                stats["fixq"] += 1

        delete_forms = [(key, key_forms(key)) for key in spec["delete"]]
        keep = []
        for d in data:
            hits = [k for k, forms in delete_forms
                    if any(f in d["question"] for f in forms)]
            if hits:
                stats["del"] += 1
                if len(hits) > 1:
                    stats["multi"] += 1
                continue
            keep.append(d)
        data = keep

        with open(path, "w", encoding="utf-8", newline="\n") as f:
            json.dump(data, f, ensure_ascii=False, indent=indent)
            f.write("\n")
        print(f"[{name}] {n0} -> {len(data)}  "
              f"fix={stats['fix']} fixq={stats['fixq']} del={stats['del']}")

    if warnings:
        print("\nWARNINGS:")
        for w in warnings:
            print("  " + w)


if __name__ == "__main__":
    main()
